#!/usr/bin/env python3
"""Generate the team search directory, HoD roster, and voting migration from one EE List."""

import argparse
from collections import Counter
import json
from pathlib import Path
import re
import runpy
import subprocess


ROOT = Path(__file__).resolve().parents[1]
RESOURCES = ROOT / 'hackhub-api/src/main/resources'
TITLES = {'mr', 'ms', 'mrs', 'dr'}


def build_voting_migration(people):
    def quote(value):
        return "'" + value.replace("'", "''") + "'"

    records = []
    for number, org, full_name in sorted(people):
        tokens = re.findall(r'[a-z0-9]+', full_name.rsplit('/', 1)[-1].lower())
        normalized = ''.join(sorted(token for token in tokens if token not in TITLES))
        if not normalized:
            raise ValueError(f'No voting match key for personnel number {number}')
        records.append((number, org, full_name, normalized))
    values = ',\n'.join('    (' + ', '.join(map(quote, record)) + ')' for record in records)
    sql = f"""-- Generated by app/scripts/refresh-bd-roster.py from the BD employee list.
CREATE TEMP TABLE bd_voting_roster_refresh (
    personnel_number TEXT PRIMARY KEY,
    organizational_unit TEXT NOT NULL,
    display_name TEXT NOT NULL,
    normalized_name TEXT NOT NULL
) ON COMMIT DROP;

INSERT INTO bd_voting_roster_refresh (personnel_number, organizational_unit, display_name, normalized_name) VALUES
{values};

INSERT INTO voting_participants (personnel_number, organizational_unit, display_name, normalized_name)
SELECT personnel_number, organizational_unit, display_name, normalized_name
FROM bd_voting_roster_refresh
ON CONFLICT (personnel_number) DO UPDATE SET
    organizational_unit = EXCLUDED.organizational_unit,
    display_name = EXCLUDED.display_name,
    normalized_name = EXCLUDED.normalized_name;

DELETE FROM voting_participants AS existing
WHERE NOT EXISTS (
    SELECT 1 FROM bd_voting_roster_refresh AS refreshed
    WHERE refreshed.personnel_number = existing.personnel_number
);
"""
    matches = Counter(record[3] for record in records)
    return sql, sum(count > 1 for count in matches.values())


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', required=True, type=Path, help='Path to the EE List workbook')
    parser.add_argument('--migration', required=True, help='New Flyway SQL filename, for example V028__refresh_bd_voting_roster.sql')
    parser.add_argument('--namelist', type=Path, help='Optional path for the generated Namelist workbook')
    parser.add_argument('--artifact-dir', type=Path, help='Directory containing @oai/artifact-tool in node_modules')
    parser.add_argument('--node', default='node', help='Node.js executable used for optional XLSX output')
    args = parser.parse_args()
    if not re.fullmatch(r'V[0-9]+__[a-z0-9_]+\.sql', args.migration):
        parser.error('--migration must be a versioned Flyway SQL filename')
    if args.namelist and not args.artifact_dir:
        parser.error('--namelist requires --artifact-dir')
    if args.namelist and args.namelist.resolve() == args.input.resolve():
        parser.error('--namelist must be a different file from --input')

    nomination = runpy.run_path(str(ROOT / 'scripts/build-nomination-roster.py'))
    directory = runpy.run_path(str(ROOT / 'scripts/build-team-member-directory.py'))
    rows = nomination['read_rows'](args.input)
    people = [(row.get('A', ''), row.get('D', ''), row.get('B', '')) for row in rows]
    if not people or any(not re.fullmatch(r'[0-9]+', number) for number, _, _ in people):
        raise ValueError('The EE List must contain employees with valid personnel numbers')
    if len({number for number, _, _ in people}) != len(people):
        raise ValueError('The EE List contains duplicate personnel numbers')
    members = directory['build_directory'](people)
    roster = nomination['build_roster'](rows)
    if any(not row['email'] or not row['hodEmail'] for row in roster):
        raise ValueError('The EE List contains an unresolved employee or HoD email')

    migration = RESOURCES / 'db/migration' / args.migration
    sql, duplicate_keys = build_voting_migration(people)
    version = int(args.migration.split('__', 1)[0][1:])
    for existing in migration.parent.glob('V*__*.sql'):
        existing_version = int(existing.name.split('__', 1)[0][1:])
        if existing_version >= version and existing != migration:
            raise ValueError(f'Choose a Flyway version newer than {existing.name}')
    if migration.exists() and migration.read_text(encoding='utf-8') != sql:
        raise ValueError(f'Will not overwrite {migration.name}; choose a new migration version')

    if args.namelist:
        args.namelist.parent.mkdir(parents=True, exist_ok=True)
        writer = (ROOT / 'scripts/write-bd-namelist.mjs').read_text(encoding='utf-8')
        subprocess.run(
            [args.node, '--input-type=module', '--eval', writer, str(args.namelist.resolve())],
            cwd=args.artifact_dir,
            input=json.dumps(people, ensure_ascii=False),
            encoding='utf-8',
            check=True,
        )

    for name, records in [('team-member-directory.json', members), ('nomination-roster.json', roster)]:
        with (RESOURCES / name).open('w', encoding='utf-8', newline='\n') as output:
            output.write(json.dumps(records, ensure_ascii=False, indent=2) + '\n')
    if not migration.exists():
        with migration.open('w', encoding='utf-8', newline='\n') as output:
            output.write(sql)
    print(json.dumps({
        'employees': len(people),
        'approvalRosterEntries': len(roster),
        'duplicateVotingMatchKeys': duplicate_keys,
        'migration': migration.name,
    }, indent=2))


if __name__ == '__main__':
    main()
